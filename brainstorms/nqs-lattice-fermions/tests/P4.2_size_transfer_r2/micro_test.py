def selftest(args):
    ok_all = True
    for (Lx, Ly) in ((4, 4), (4, 2), (2, 2)):
        lat = Torus(Lx, Ly, 1.0, -0.25, 0.0)
        eps = np.sort(-2 * (np.cos(lat.kx) + np.cos(lat.ky)) - 4 * (-0.25) * np.cos(lat.kx) * np.cos(lat.ky))
        for nf in (1, 3):
            basis = make_basis(lat.N, nf, 0)
            Hs = build_H(lat, basis, spinful=False)
            herm = abs(Hs - Hs.T).max()
            e = np.linalg.eigvalsh(Hs.toarray())[0]
            ref = eps[:nf].sum()
            ok = abs(e - ref) < 1e-10 and herm < 1e-12
            ok_all &= ok
            log(f"selftest(a) spinless {Lx}x{Ly} N_f={nf}: E_ED={e:.10f} band={ref:.10f} {'OK' if ok else 'FAIL'}")
    # (b)-(d) on 4x2, 2 holes
    lat = Torus(4, 2, args.t, args.tp, args.J)
    basis = make_basis(lat.N, 3, 3)
    H = build_H(lat, basis)
    herm = abs(H - H.T).max()
    ok_all &= herm < 1e-12
    log(f"selftest(b) t-J 4x2 2 holes dim={len(basis)} herm={herm:.1e} {'OK' if herm < 1e-12 else 'FAIL'}")
    rng = np.random.default_rng(1)
    net = new_net(lat, 3, args)
    th = net.init(rng, 6 / 8, args.t, args.tp, args.delta0, args.eta)
    th = th + 0.05 * rng.standard_normal(len(th))
    psi = state_vector(net, th, basis, args.chunk)
    mz = MomentumZero(lat, basis)
    ox = psi @ mz.apply(mz.Tx, psi); oy = psi @ mz.apply(mz.Ty, psi)
    proj = float(np.linalg.norm(mz.reduce(psi)) ** 2)
    Hk = (mz.U.T @ H @ mz.U).tocsr()
    wk = np.linalg.eigvalsh(Hk.toarray())
    wf = np.linalg.eigvalsh(H.toarray())
    ins = all(np.min(np.abs(wf - e)) < 1e-9 for e in wk)
    ok = abs(ox - 1) < 1e-10 and abs(oy - 1) < 1e-10 and abs(proj - 1) < 1e-10 and ins
    ok_all &= ok
    log(f"selftest(c) <psi|T_x psi>={ox:.12f} <psi|T_y psi>={oy:.12f} |U^T psi|^2={proj:.12f}; "
        f"k=0 block ({mz.n_orb} orbits) spectrum inside full spectrum: {ins} {'OK' if ok else 'FAIL'}")
    sub = basis[::7]
    la, sg, O = net.evaluate(th, sub, True)
    err = 0.0
    for p in range(net.npar):
        e = np.zeros(net.npar); e[p] = 1e-6
        lp, sp_, _ = net.evaluate(th + e, sub, False)
        lm, sm, _ = net.evaluate(th - e, sub, False)
        # exclude configurations within e^-8 of a node (finite differences unreliable there)
        fin = np.isfinite(lp) & np.isfinite(lm) & np.isfinite(la) & (sp_ == sm)
        fin &= la > np.median(la[np.isfinite(la)]) - 8
        fd = (lp - lm)[fin] / 2e-6
        err = max(err, float(np.max(np.abs(fd - O[fin, p])) / (1 + np.max(np.abs(fd)))))
    ok = err < 1e-5
    ok_all &= ok
    log(f"selftest(d) log-derivative max rel err over {net.npar} params = {err:.2e} {'OK' if ok else 'FAIL'}")
    src, tgt = Torus(*parse_lat(args.src), 1, 0, 0), Torus(*parse_lat(args.tgt), 1, 0, 0)
    key = lambda kx, ky: (round((np.cos(kx) + np.cos(ky)) / 2, 9), round(np.cos(kx) * np.cos(ky), 9),
                          round(abs(np.cos(kx) - np.cos(ky)), 9))
    ks = {key(a, b) for a, b in zip(src.kx, src.ky)}
    kt = [(a, b) for a, b in zip(tgt.kx, tgt.ky)]
    new = [(round(a / np.pi, 3), round(b / np.pi, 3)) for a, b in kt if key(a, b) not in ks]
    log(f"selftest(e) {src.name()} -> {tgt.name()}: {len(kt)} target momenta, "
        f"{len(kt) - len(new)} on source C4v orbits, new (units of pi): {new}")
    log("SELFTEST", "PASSED" if ok_all else "FAILED")
    return ok_all


