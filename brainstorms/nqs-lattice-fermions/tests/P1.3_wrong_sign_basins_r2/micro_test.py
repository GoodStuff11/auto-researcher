# ----------------------------------------------------------------------------- symmetry
def group(model):
    """All space-group elements g = Tx^a Ty^b Mx^c My^d as (exponents, site perm)."""
    Lx, Ly, V = model.Lx, model.Ly, model.V
    out = []
    for c in (0, 1):
        for d in (0, 1):
            for a in range(Lx):
                for b in range(Ly):
                    p = np.empty(V, dtype=np.int64)
                    for y in range(Ly):
                        for x in range(Lx):
                            x2 = (-x) % Lx if c else x
                            y2 = (-y) % Ly if d else y
                            x2, y2 = (x2 + a) % Lx, (y2 + b) % Ly
                            p[x + Lx * y] = x2 + Lx * y2
                    out.append(((a, b, c, d), p))
    return out


def vector_maps(model, perms):
    st_u, lk_u, _, rows_u = P.species_basis(model.V, model.nup)
    st_d, lk_d, _, rows_d = P.species_basis(model.V, model.ndn)
    return [(e, (species_perm(st_u, rows_u, lk_u, p), species_perm(st_d, rows_d, lk_d, p)))
            for e, p in perms]


def gen_expect(model, psi, gmaps):
    """<Tx>, <Ty>, <Mx>, <My> of normalised psi."""
    want = {(1, 0, 0, 0): "Tx", (0, 1, 0, 0): "Ty", (0, 0, 1, 0): "Mx", (0, 0, 0, 1): "My"}
    psi = psi / np.linalg.norm(psi)
    return {want[e]: float(psi @ apply_op(model, psi, mp)) for e, mp in gmaps if e in want}


def real_irreps(model):
    """All real 1-D irreps as generator eigenvalues {Tx, Ty, Mx, My} in {+1,-1}
    (Tx = -1 only for even Lx, Ty = -1 only for even Ly)."""
    out = []
    for lx in ((1, -1) if model.Lx % 2 == 0 else (1,)):
        for ly in ((1, -1) if model.Ly % 2 == 0 else (1,)):
            for mx in (1, -1):
                for my in (1, -1):
                    out.append(dict(Tx=lx, Ty=ly, Mx=mx, My=my))
    return out


def project_chi(model, psi, lam, gmaps):
    out = np.zeros_like(psi)
    for (a, b, c, d), mp in gmaps:
        out += lam["Tx"] ** a * lam["Ty"] ** b * lam["Mx"] ** c * lam["My"] ** d * apply_op(model, psi, mp)
    return out


def irrep_scan(m, a, psi, ctx):
    """Route P (irrep scan with FN-ranked selection), post-hoc on a trained state:
    for every real 1-D irrep chi, project psi, record E_var and the guided FN score of the
    projection; pick chi by FN score ('fn') and by E_var ('var'); compute E_sign of the
    FN-selected projection. 'correct' = chi of psi_0."""
    ev0 = gen_expect(m, ctx["psi0"], ctx["gmaps"])
    rows = []
    for lam in real_irreps(m):
        pp = project_chi(m, psi, lam, ctx["gmaps"])
        nrm = np.linalg.norm(pp)
        if nrm < 1e-8 * np.linalg.norm(psi):
            continue
        pp /= nrm
        rows.append(dict(irrep=lam, weight=float(nrm ** 2 / (psi @ psi) / len(ctx["gmaps"]) ** 2),
                         E_var=P.energy(m.H, pp)[0], fn_score=fn_guided(m.H, pp, a.fn_floor),
                         correct=all(abs(lam[k] - ev0[k]) < 1e-6 for k in lam)))
    pick_fn = min(rows, key=lambda r: r["fn_score"])
    pick_var = min(rows, key=lambda r: r["E_var"])
    pp = project_chi(m, psi, pick_fn["irrep"], ctx["gmaps"]); pp /= np.linalg.norm(pp)
    p0 = ctx["psi0"] if ctx["psi0"] @ pp >= 0 else -ctx["psi0"]
    sel = dict(E=P.energy(m.H, pp)[0], **esign(m, a, pp, p0))
    return dict(rows=rows, fn_correct=pick_fn["correct"], var_correct=pick_var["correct"],
                psi0_in_real_irrep=any(r["correct"] for r in rows), selected=sel)


def irrep_project(model, psi, ref, gmaps):
    """Project psi on the 1-D irrep of ref (generator eigenvalues rounded to +-1);
    returns None if ref is not in a real 1-D irrep."""
    ev = gen_expect(model, ref, gmaps)
    if any(abs(abs(v) - 1) > 1e-6 for v in ev.values()):
        return None
    lam = {k: round(v) for k, v in ev.items()}
    out = np.zeros_like(psi)
    for (a, b, c, d), mp in gmaps:
        chi = lam["Tx"] ** a * lam["Ty"] ** b * lam["Mx"] ** c * lam["My"] ** d
        out += chi * apply_op(model, psi, mp)
    return out


# ----------------------------------------------------------------------------- 1-RDM / NOs
def one_body_ops(V, N):
    """ops[i][j] = matrix of a^dag_i a_j on the N-particle species space."""
    ops = [[None] * V for _ in range(V)]
    for i in range(V):
        for j in range(V):
            ops[i][j] = _hop_nonsym(V, N, i, j)
    return ops


def _hop_nonsym(V, N, i, j):
    st, lk, _, _ = P.species_basis(V, N)
    r, c, v = [], [], []
    for k, b in enumerate(st):
        if not (b >> j) & 1:
            continue
        b1 = b ^ (1 << j); s1 = P.popcount_below(b, j)
        if (b1 >> i) & 1:
            continue
        b2 = b1 | (1 << i); s2 = P.popcount_below(b1, i)
        r.append(lk[b2]); c.append(k); v.append((-1.0) ** (s1 + s2))
    return sp.csr_matrix((v, (r, c)), shape=(len(st), len(st)))


def rdm1(model, psi, ops_u, ops_d):
    Psi = (psi / np.linalg.norm(psi)).reshape(model.Du, model.Dd)
    V = model.V
    ru, rd = np.zeros((V, V)), np.zeros((V, V))
    for i in range(V):
        for j in range(V):
            ru[i, j] = np.sum(Psi * (ops_u[i][j] @ Psi))
            rd[i, j] = np.sum(Psi * (ops_d[i][j] @ Psi.T).T)
    return ru, rd


def sym_nos(rho, perms):
    """Group-averaged 1-RDM and its eigenvectors (descending occupation); degenerate
    shells are split by an infinitesimal mirror-parity term."""
    V = rho.shape[0]
    R = np.zeros_like(rho)
    Pm = {}
    for e, p in perms:
        Pg = np.zeros((V, V)); Pg[p, np.arange(V)] = 1.0
        R += Pg @ rho @ Pg.T
        Pm[e] = Pg
    R /= len(perms)
    split = 1e-7 * (Pm[(0, 0, 0, 1)] + 0.5 * Pm[(0, 0, 1, 0)])
    split = 0.5 * (split + split.T)
    w, U = np.linalg.eigh(R + split)
    o = np.argsort(-w)
    return w[o], U[:, o]


# ----------------------------------------------------------------------------- SR engine
def clone(ans):
    new = copy.copy(ans)
    new.p = {k: v.copy() for k, v in ans.p.items()}
    return new


def sr_step(ans, H, rng, a, extra=None):
    """One P1.1 SR step (exact force, sampled metric). extra(ans, psi, nn) adds to the
    half-gradient force. Returns the energy before the step."""
    psi = ans.amplitudes(a.chunk)
    E, Hp, nn = P.energy(H, psi)
    f = ans.grad_weighted(psi * (Hp - E * psi) / nn, a.chunk)
    if extra is not None:
        f = f + extra(ans, psi, nn)
    p = psi ** 2 / nn
    idx = rng.choice(len(psi), size=a.sr_samples, p=p)
    O = ans.per_sample_O_fast(idx)
    Oc = (O - O.mean(0)) / np.sqrt(len(idx))
    lam = a.sr_shift
    Km = Oc @ Oc.T + lam * np.eye(len(idx))
    dx = (f - Oc.T @ np.linalg.solve(Km, Oc @ f)) / lam
    step = a.sr_lr * dx
    nrm = np.linalg.norm(step)
    if nrm > 1.0:
        step /= nrm
    ans.set_flat(ans.flat() - step)
    return E


def sr_run(ans, H, n, rng, a, label, extra=None, final_window=0):
    """n SR steps; if final_window > 0 the lowest-energy iterate of the last
    final_window steps (or the final state) is restored."""
    best = (np.inf, None)
    for it in range(n):
        x = ans.flat().copy()
        E = sr_step(ans, H, rng, a, extra)
        if not np.isfinite(E):
            ans.set_flat(x); break
        if final_window and it >= n - final_window and E < best[0]:
            best = (E, x)
        if it % 100 == 0:
            log(f"  {label}: it {it} E={E:.6f}")
    if final_window:
        Ef = P.energy(H, ans.amplitudes(a.chunk))[0]
        if best[1] is not None and best[0] < Ef:
            ans.set_flat(best[1])
    return ans


def fidelity_force(ans, psi, nn, ref, a):
    """Half-gradient of F = <ref|psi>^2/(<ref|ref><psi|psi>) and F itself."""
    ov = ref @ psi
    F = ov * ov / (nn * (ref @ ref))
    g1 = ans.grad_weighted(ref * psi / ov, a.chunk)
    g2 = ans.grad_weighted(psi * psi / nn, a.chunk)
    return F, F * (g1 - g2)  # dF/dtheta = 2 F (g1 - g2); half of it


# ----------------------------------------------------------------------------- scores
def fn_guided(H, psi, floor):
    """One ten Haaf solve with guide |psi| and signs sgn(psi) (lattice FN-GFMC target)."""
    s = np.where(psi >= 0, 1.0, -1.0)
    S = sp.diags(s)
    K = (S @ H @ S).tocsr().tocoo()
    off = K.row != K.col
    r, c, v = K.row[off], K.col[off], K.data[off]
    bad = v > 0
    g = np.abs(psi) / np.abs(psi).max()
    g = np.maximum(g, floor)
    D = H.shape[0]
    d = H.diagonal() + np.bincount(r[bad], weights=v[bad] * g[c[bad]] / g[r[bad]], minlength=D)
    Heff = sp.csr_matrix((v[~bad], (r[~bad], c[~bad])), shape=(D, D)) + sp.diags(d)
    w, _ = P._lowest(Heff.tocsr(), np.abs(psi) / np.linalg.norm(psi))
    return float(w[0])


def score(ans, m, a, kind):
    psi = ans.amplitudes(a.chunk)
    if kind == "energy":
        return P.energy(m.H, psi)[0]
    return fn_guided(m.H, psi, a.fn_floor)


# ----------------------------------------------------------------------------- arms
def new_start(m, seed, width):
    Pu, Pd = P.uhf_orbitals(m, seed)
    return P.Ansatz(m, Pu, Pd, "nnbf", width=width, jastrow=False, seed=seed + width)


def run_S(m, a, seed, rng, ctx):
    ans = new_start(m, seed, a.width)
    return sr_run(ans, m.H, a.budget, rng, a, "S", final_window=a.final_window), {}


def proposal_steps(a, n_cand):
    return a.warmup + a.cycles * (n_cand + 1) * a.relax


def sno_candidates(ans, m, a, ctx):
    psi = ans.amplitudes(a.chunk)
    ru, rd = rdm1(m, psi, ctx["ops_u"], ctx["ops_d"])
    wu, Uu = sym_nos(ru, ctx["perms"])
    wd, Ud = sym_nos(rd, ctx["perms"])
    nu, nd = m.nup, m.ndn

    def occ(U, n, swap):
        cols = list(range(n))
        if swap:
            cols[-1] = n
        return U[:, cols].copy()

    out = []
    for name, su, sd in (("sno", 0, 0), ("swap_u", 1, 0), ("swap_d", 0, 1), ("swap_ud", 1, 1)):
        c = clone(ans)
        c.p["Pu"] = occ(Uu, nu, su); c.p["Pd"] = occ(Ud, nd, sd)
        out.append((name, c))
    info = dict(no_occ_u=wu.tolist(), no_occ_d=wd.tolist())
    return out, info


def hop_loop(m, a, rng, ans, make_cands, kind, label):
    """Shared cycle skeleton for A, AE, B. Returns (ans, history, steps_used)."""
    used = 0
    hist = []
    for cyc in range(a.cycles):
        cands, info = make_cands(ans)
        used += sum(st for _, _, st in cands)
        inc = sr_run(clone(ans), m.H, a.relax, rng, a, f"{label} inc")
        used += a.relax
        sc_inc = score(inc, m, a, kind)
        best = ("stay", inc, sc_inc)
        rows = [("stay", sc_inc)]
        for name, c, _ in cands:
            c = sr_run(c, m.H, a.relax, rng, a, f"{label} {name}")
            used += a.relax
            sc = score(c, m, a, kind)
            rows.append((name, sc))
            if sc < best[2]:
                best = (name, c, sc)
        ans = best[1]
        hist.append(dict(cycle=cyc, scores=rows, chosen=best[0], **info))
        log(f"{label} cycle {cyc}: " + " ".join(f"{n}={s:.5f}" for n, s in rows) + f" -> {best[0]}")
    return ans, hist, used


def run_A(m, a, seed, rng, ctx, kind="fn", label="A"):
    ans = new_start(m, seed, a.width)
    sr_run(ans, m.H, a.warmup, rng, a, label)

    def mk(cur):
        cands, info = sno_candidates(cur, m, a, ctx)
        return [(n, c, 0) for n, c in cands], info

    ans, hist, used = hop_loop(m, a, rng, ans, mk, kind, label)
    rest = a.budget - a.warmup - used
    sr_run(ans, m.H, rest, rng, a, label, final_window=a.final_window)
    return ans, dict(history=hist, steps=a.warmup + used + rest)


def run_B(m, a, seed, rng, ctx):
    ans = new_start(m, seed, a.width)
    sr_run(ans, m.H, a.warmup, rng, a, "B")

    def mk(cur):
        ref = cur.amplitudes(a.chunk)
        out = []
        for cap in a.cap_list:
            c = clone(cur)
            Fs = []

            def extra(an, psi, nn, ref=ref, cap=cap, Fs=Fs):
                F, dF = fidelity_force(an, psi, nn, ref, a)
                Fs.append(F)
                return 2.0 * a.lam * max(0.0, F - cap) * dF  # half-gradient of lam*max(0,F-c)^2 (dF is half of dF/dtheta)
            sr_run(c, m.H, a.excursion, rng, a, f"B exc c={cap}", extra=extra)
            out.append((f"cap{cap}", c, a.excursion))
        return out, {}

    ans, hist, used = hop_loop(m, a, rng, ans, mk, "fn", "B")
    rest = a.budget - a.warmup - used
    sr_run(ans, m.H, rest, rng, a, "B", final_window=a.final_window)
    return ans, dict(history=hist, steps=a.warmup + used + rest)


def run_N(m, a, seed, rng, ctx):
    L = proposal_steps(a, 4) // a.null_k
    starts = []
    for j in range(a.null_k):
        ans = new_start(m, seed + 7919 * j, a.width)
        sr_run(ans, m.H, L, rng, a, f"N{j}")
        starts.append((score(ans, m, a, "fn"), j, ans))
    starts.sort(key=lambda z: z[0])
    sc, j, ans = starts[0]
    rest = a.budget - L * a.null_k
    sr_run(ans, m.H, rest, rng, a, "N", final_window=a.final_window)
    return ans, dict(scores=[(jj, s) for s, jj, _ in starts], chosen=j, L=L, steps=L * a.null_k + rest)


def run_W(m, a, seed, rng, ctx):
    ans = new_start(m, seed, a.width)
    ref = ctx["psi0"]

    def extra(an, psi, nn):
        E, Hp, _ = P.energy(m.H, psi)
        f_e = an.grad_weighted(psi * (Hp - E * psi) / nn, a.chunk)
        F, dF = fidelity_force(an, psi, nn, ref, a)
        return -f_e - dF / max(F, 1e-12)  # replace energy force by half-grad of -log F
    sr_run(ans, m.H, a.pretrain, rng, a, "W pre", extra=extra)
    psi = ans.amplitudes(a.chunk)
    F0 = float((psi @ ref) ** 2 / (psi @ psi))
    sr_run(ans, m.H, a.budget, rng, a, "W", final_window=a.final_window)
    return ans, dict(F_after_pretrain=F0)


# ----------------------------------------------------------------------------- evaluation
def evaluate(m, a, ans, ctx, rng, project=False):
    W, Vv = ctx["W"], ctx["Vv"]
    psi = ans.amplitudes(a.chunk); psi /= np.linalg.norm(psi)
    p0 = ctx["psi0"]
    if p0 @ psi < 0:
        p0 = -p0
    E = P.energy(m.H, psi)[0]
    out = dict(E=E, **esign(m, a, psi, p0))
    out["w_sign"] = float(np.sum(p0[np.sign(psi) * np.sign(p0) < 0] ** 2))
    out["overlaps"] = [float((Vv[:, k] @ psi) ** 2) for k in range(Vv.shape[1])]
    out["sym"] = gen_expect(m, psi, ctx["gmaps"])
    if project:
        pp = irrep_project(m, psi, ctx["psi0"], ctx["gmaps"])
        if pp is not None and np.linalg.norm(pp) > 1e-10:
            pp /= np.linalg.norm(pp)
            out["proj"] = dict(E=P.energy(m.H, pp)[0], **esign(m, a, pp, p0 if p0 @ pp >= 0 else -p0))
        out["scan"] = irrep_scan(m, a, psi, ctx)
    return out


def esign(m, a, psi, p0):
    s = np.where(psi >= 0, 1.0, -1.0)
    S = sp.diags(s)
    K = (S @ m.H @ S).tocsr()
    E_FN, E_FN_var, phi, _ = P.fixed_node(K, a.fn_iters, a.fn_floor)
    E_lb, _, starts = P.sign_constrained_min(
        K, [("abs_theta", psi), ("abs_fixed_node", phi), ("abs_exact", p0)], a.lbfgs_iters)
    E_sign = min(E_lb, E_FN, E_FN_var)
    return dict(E_sign=E_sign, E_FN=E_FN, E_FN_var=E_FN_var,
                sign_starts=[(n, e) for n, e, _, _ in starts])


# ----------------------------------------------------------------------------- checks
def run_checks(seed):
    ok = P.run_checks(seed)
    m = P.Hubbard(3, 2, "pbc", "obc", 2, 2, 1.0, -0.25, 6.0)
    W, Vv, deg = P.solve_ed(m, 3, 1e-8, seed)
    psi0 = Vv[:, 0]
    # (1) ten Haaf with exact sign and exact guide returns E_0
    e = fn_guided(m.H, psi0, 1e-6)  # psi0 has exact symmetry zeros; floor them
    log(f"check FN(exact sign, guide |psi0|) - E0 = {e - W[0]:.2e}"); ok &= abs(e - W[0]) < 1e-8
    # (2) 1-RDM trace and U=0 natural orbitals reproduce the free Slater energy
    ops_u, ops_d = one_body_ops(m.V, m.nup), one_body_ops(m.V, m.ndn)
    ru, rd = rdm1(m, psi0, ops_u, ops_d)
    log(f"check tr rho_u={np.trace(ru):.10f} (N_up={m.nup}) tr rho_d={np.trace(rd):.10f}")
    ok &= abs(np.trace(ru) - m.nup) < 1e-10 and abs(np.trace(rd) - m.ndn) < 1e-10
    m0 = P.Hubbard(3, 2, "pbc", "obc", 2, 2, 1.0, -0.25, 0.0)
    W0, V0, _ = P.solve_ed(m0, 2, 1e-8, seed)
    ru0, rd0 = rdm1(m0, V0[:, 0], ops_u, ops_d)
    _, Uu = np.linalg.eigh(-ru0); _, Ud = np.linalg.eigh(-rd0)
    sl = P.Ansatz(m0, Uu[:, :2], Ud[:, :2], "slater")
    Es = P.energy(m0.H, sl.amplitudes(4096))[0]
    log(f"check U=0 NO Slater E={Es:.10f} ED={W0[0]:.10f}"); ok &= abs(Es - W0[0]) < 1e-8
    # (3) space group commutes with H (3x3 PBC) and psi0 irrep projection is psi0
    m3 = P.Hubbard(3, 3, "pbc", "pbc", 3, 3, 1.0, -0.25, 8.0)  # non-degenerate psi0, k=0, Mx=My=-1
    gm = vector_maps(m3, group(m3))
    v = np.random.default_rng(seed).standard_normal(m3.D)
    err = max(np.linalg.norm(apply_op(m3, m3.H @ v, mp) - m3.H @ apply_op(m3, v, mp)) for _, mp in gm)
    log(f"check max ||[H,g]v|| over {len(gm)} group elements = {err:.1e}"); ok &= err < 1e-9
    W3, V3, d3 = P.solve_ed(m3, 2, 1e-8, seed)
    pp = irrep_project(m3, V3[:, 0], V3[:, 0], gm)
    if pp is not None:
        c = abs(pp @ V3[:, 0]) / np.linalg.norm(pp)
        log(f"check irrep projection of psi0 overlap = {c:.12f}"); ok &= abs(c - 1) < 1e-8
    else:
        log("check irrep projection: psi0 not in a real 1-D irrep (skipped)")
    # (4) fidelity force vs finite difference
    Pu, Pd = P.uhf_orbitals(m, seed)
    an = P.Ansatz(m, Pu, Pd, "nnbf", width=4, seed=seed); an.p["W2"] *= 100

    class _A: chunk = 4096
    x0 = an.flat().copy(); psi = an.amplitudes(4096)
    F, dF = fidelity_force(an, psi, psi @ psi, psi0, _A)
    d = np.random.default_rng(1).standard_normal(len(x0)); d /= np.linalg.norm(d)
    h = 1e-6

    def Fof(x):
        an.set_flat(x); q = an.amplitudes(4096)
        return (q @ psi0) ** 2 / (q @ q)
    fd = (Fof(x0 + h * d) - Fof(x0 - h * d)) / (2 * h); an.set_flat(x0)
    log(f"check fidelity grad: analytic {2 * dF @ d:.8e} fd {fd:.8e}")
    ok &= abs(2 * dF @ d - fd) < 1e-6 * max(1, abs(fd))
    log(f"P1.3 r2 CHECKS {'PASSED' if ok else 'FAILED'}")
    return ok


# ----------------------------------------------------------------------------- aggregate
def aggregate(d):
    import glob
    allrows = [json.load(open(f)) for f in sorted(glob.glob(os.path.join(d, "*.json")))]
    for inst in sorted({r.get("instance", "?") for r in allrows}):
        print(f"===== instance {inst} =====")
        aggregate_rows([r for r in allrows if r.get("instance", "?") == inst])
    return 0


def aggregate_rows(rows):
    need = ("S", "N", "A", "B")
    rows = [r for r in rows if all(k in r["arms"] for k in need)]
    n = len(rows)
    print(f"{n} complete seed file(s)")
    if n == 0:
        return 1
    E0 = lambda r: r["ed"][0]
    e = {k: [] for k in ("S", "N", "A", "AE", "B", "W")}
    for r in rows:
        print(f"seed {r['seed']}: " + "  ".join(
            f"{k}: Esgn-E0={r['arms'][k]['eval']['E_sign'] - E0(r):.4f} Ev={r['arms'][k]['eval']['E']:.4f}"
            for k in e if k in r["arms"]))
    res = {}
    base = np.array([min(r["arms"]["S"]["eval"]["E_sign"], r["arms"]["N"]["eval"]["E_sign"]) - E0(r) for r in rows])
    evb = np.array([min(r["arms"]["S"]["eval"]["E"], r["arms"]["N"]["eval"]["E"]) for r in rows])
    kmin = math.ceil(7 * n / 8)
    for R in ("A", "B", "AE"):
        if not all(R in r["arms"] for r in rows):
            continue
        eR = np.array([r["arms"][R]["eval"]["E_sign"] - E0(r) for r in rows])
        rho = (base - eR) / base
        dev = np.array([r["arms"][R]["eval"]["E"] for r in rows]) - evb
        med, npos, mdev = float(np.median(rho)), int(np.sum(rho > 0)), float(np.median(dev))
        if med >= PASS_MED and npos >= kmin and mdev <= EVAR_TOL:
            v = "PASS"
        elif med < FAIL_MED or npos <= n / 2:
            v = "FAIL"
        else:
            v = "AMBIGUOUS (rerun with 16 more seeds; kill unless PASS)"
        if v == "PASS" and all("proj" in r["arms"]["S"]["eval"] for r in rows):
            eP = np.array([r["arms"]["S"]["eval"]["proj"]["E_sign"] - E0(r) for r in rows])
            if np.median(eR) >= np.median(eP):
                v = "PASS but DOMINATED by psi0-irrep projection of S (claim reduces to cost: no |G| overhead)"
        res[R] = (med, npos, mdev, v)
        print(f"route {R}: median rho={med:.3f}  rho>0 on {npos}/{n} (need {kmin})  "
              f"median dEvar={mdev:+.4f} -> {v}")
    if all("scan" in r["arms"]["S"]["eval"] for r in rows):
        sc = [r["arms"]["S"]["eval"]["scan"] for r in rows]
        fn_c = sum(s["fn_correct"] for s in sc); var_c = sum(s["var_correct"] for s in sc)
        eS = np.array([r["arms"]["S"]["eval"]["E_sign"] - E0(r) for r in rows])
        eP = np.array([s["selected"]["E_sign"] - E0(r) for s, r in zip(sc, rows)])
        medP = float(np.median((eS - eP) / eS))
        if fn_c >= kmin and var_c <= fn_c - 2 and medP >= PASS_MED:
            v = "PASS"
        elif fn_c <= n - 3 or var_c >= fn_c:
            v = "FAIL" + (" (FN gate adds nothing over energy ranking: standard projection)"
                          if var_c >= fn_c and fn_c > n - 3 else "")
        else:
            v = "AMBIGUOUS (rerun with 16 more seeds; kill unless PASS)"
        print(f"route P (irrep scan, FN-ranked): FN picks psi0 irrep {fn_c}/{n}, "
              f"E_var picks it {var_c}/{n}, median rho_P={medP:.3f} -> {v}")
    if all("W" in r["arms"] for r in rows):
        eS = np.array([r["arms"]["S"]["eval"]["E_sign"] - E0(r) for r in rows])
        eW = np.array([r["arms"]["W"]["eval"]["E_sign"] - E0(r) for r in rows])
        g = (eS - eW) / eS
        med, npos = float(np.median(g)), int(np.sum(g > 0))
        prem = ("BASIN" if med >= BASIN_MED and npos >= kmin else
                "NO-BASIN" if med < NOBASIN_MED else "UNCLEAR")
        print(f"premise (witness): median gW={med:.3f}  gW>0 on {npos}/{n} -> {prem}")
        for R, (_, _, _, v) in res.items():
            if prem == "NO-BASIN" and v == "PASS":
                print(f"  route {R}: PASS (optimizer speed-up, not basin escape)")
    if "A" in res and "AE" in res:
        print(f"ablation: median rho_A - median rho_AE = {res['A'][0] - res['AE'][0]:+.3f}")
    if n < 8:
        print("NOTE: fewer than 8 seeds; the verdict above is not decisive.")
    return 0


# ----------------------------------------------------------------------------- main
def parse_args(argv=None):
    ap = argparse.ArgumentParser(description="P1.3 round-2 decisive test (see module docstring)")
    ap.add_argument("--instance", choices=list(INST), default="main")
    ap.add_argument("--seed", type=int, default=1234)
    ap.add_argument("--arms", default="S,N,A,AE,B,W")
    ap.add_argument("--width", type=int, default=32)
    ap.add_argument("--budget", type=int, default=1200)
    ap.add_argument("--warmup", type=int, default=300)
    ap.add_argument("--cycles", type=int, default=2)
    ap.add_argument("--relax", type=int, default=40)
    ap.add_argument("--excursion", type=int, default=60)
    ap.add_argument("--caps", default="0.8,0.5")
    ap.add_argument("--lam", type=float, default=2.0)
    ap.add_argument("--null-k", type=int, default=3)
    ap.add_argument("--pretrain", type=int, default=300)
    ap.add_argument("--final-window", type=int, default=100)
    ap.add_argument("--sr-lr", type=float, default=0.05)
    ap.add_argument("--sr-shift", type=float, default=1e-3)
    ap.add_argument("--sr-samples", type=int, default=2000)
    ap.add_argument("--chunk", type=int, default=65536)
    ap.add_argument("--fn-iters", type=int, default=4)
    ap.add_argument("--fn-floor", type=float, default=1e-3)
    ap.add_argument("--lbfgs-iters", type=int, default=3000)
    ap.add_argument("--n-ed", type=int, default=4)
    ap.add_argument("--out", default="")
    ap.add_argument("--overwrite", type=int, choices=[0, 1], default=0)
    ap.add_argument("--checks-only", type=int, choices=[0, 1], default=0)
    ap.add_argument("--aggregate", default="")
    a = ap.parse_args(argv)
    a.arm_list = [x.strip() for x in a.arms.split(",") if x.strip()]
    bad = set(a.arm_list) - {"S", "N", "A", "AE", "B", "W"}
    if bad:
        ap.error(f"unknown arms {bad}")
    a.cap_list = [float(x) for x in a.caps.split(",")]
    if not all(0 < c < 1 for c in a.cap_list):
        ap.error("--caps must lie in (0,1)")
    a.n_ed = max(3, a.n_ed)
    for k, steps in (("A", proposal_steps(a, 4)),
                     ("B", a.warmup + a.cycles * (len(a.cap_list) * (a.excursion + a.relax) + a.relax))):
        if steps + a.final_window > a.budget:
            ap.error(f"arm {k} proposal phase ({steps}) + final window exceeds --budget")
    if not a.out:
        a.out = os.path.join(HERE, "results", f"seed{a.seed}_{a.instance}.json")
    return a


def main(argv=None):
    a = parse_args(argv)
    if a.aggregate:
        return aggregate(a.aggregate)
    if not run_checks(a.seed):
        return 2
    if a.checks_only:
        return 0
    if os.path.exists(a.out) and not a.overwrite:
        log(f"{a.out} exists; use --overwrite 1"); return 0
    c = INST[a.instance]
    m = P.Hubbard(c["Lx"], c["Ly"], c["bcx"], c["bcy"], c["nup"], c["ndn"], 1.0, c["tp"], c["U"])
    t0 = time.time()
    W, Vv, deg = P.solve_ed(m, a.n_ed, 1e-8, 1234)
    perms = group(m)
    ctx = dict(W=W, Vv=Vv, psi0=Vv[:, 0] / np.linalg.norm(Vv[:, 0]), perms=perms,
               gmaps=vector_maps(m, perms),
               ops_u=one_body_ops(m.V, m.nup), ops_d=one_body_ops(m.V, m.ndn))
    log(f"instance {a.instance} D={m.D} ED {W.tolist()} deg={deg} setup {time.time() - t0:.1f}s")
    res = dict(instance=a.instance, seed=a.seed, params={k: v for k, v in vars(a).items()},
               ed=W.tolist(), arms={})
    runners = dict(S=run_S, N=run_N, A=run_A, B=run_B, W=run_W,
                   AE=lambda m_, a_, s_, r_, c_: run_A(m_, a_, s_, r_, c_, kind="energy", label="AE"))
    for k in a.arm_list:
        t1 = time.time()
        rng = np.random.default_rng([a.seed, ord(k[0]), len(k)])
        ans, info = runners[k](m, a, a.seed, rng, ctx)
        ev = evaluate(m, a, ans, ctx, rng, project=(k == "S"))
        res["arms"][k] = dict(info=info, eval=ev, seconds=time.time() - t1)
        log(f"ARM {k}: E={ev['E']:.6f} E_sign-E0={ev['E_sign'] - W[0]:.5f} "
            f"E_FN-E0={ev['E_FN'] - W[0]:.5f} w_sign={ev['w_sign']:.3f} "
            f"ov={[round(x, 3) for x in ev['overlaps']]} sym={ {q: round(v, 3) for q, v in ev['sym'].items()} }"
            + (f" proj: E_sign-E0={ev['proj']['E_sign'] - W[0]:.5f}" if "proj" in ev else "")
            + (f" scan: fn_correct={ev['scan']['fn_correct']} var_correct={ev['scan']['var_correct']} "
               f"sel E_sign-E0={ev['scan']['selected']['E_sign'] - W[0]:.5f} "
               + " ".join(f"[{''.join('+' if v > 0 else '-' for v in r['irrep'].values())} "
                          f"wt={r['weight']:.3f} Ev={r['E_var']:.4f} FN={r['fn_score']:.4f}]"
                          for r in ev['scan']['rows']) if "scan" in ev else "")
            + f" ({time.time() - t1:.0f}s)")
        os.makedirs(os.path.dirname(a.out), exist_ok=True)
        with open(a.out, "w") as fh:
            json.dump(res, fh, indent=1, default=float)
    log(f"wrote {a.out} total {time.time() - t0:.0f}s")
    return 0


if __name__ == "__main__":
    sys.exit(main())
