#!/usr/bin/env python3
"""
P1.3 round-2 decisive test: do NNBF trajectories sit in an escapable wrong-sign basin,
and do (A) symmetrized-natural-orbital re-anchoring with fixed-node-gated acceptance
(SNO-FN) or (B) fidelity-capped deflation excursions (FCD) reduce the sign error
E_sign at a matched SR-step budget, beyond plain SR and beyond matched restarts?

Physics code (Hubbard model, ED, NNBF ansatz, exact-force SR, ten Haaf fixed node,
sign-constrained L-BFGS-B) is imported from p11_core.py, a verbatim copy of the P1.1
test (tests/P1.1_sign_vs_amplitude/micro_test.py). Lattice-symmetry maps are imported
from diag_sectors.py in this folder.

What one run does (one seed; production runs one seed per Slurm array task)
--------------------------------------------------------------------------
1. Builds the instance, runs ED (lowest --n-ed eigenpairs), and builds the 48 (or, for
   other lattices, |G|) space-group maps generated by Tx, Ty, Mx, My.
2. Runs every arm listed in --arms from the SAME seed-dependent start (UHF reference with
   seed s, NNBF weights with seed s). Each arm spends exactly --budget SR steps (the
   witness spends --pretrain extra fidelity steps first). SR is the P1.1 scheme: exact
   force, metric from --sr-samples configurations drawn exactly from |psi|^2, step
   --sr-lr, shift --sr-shift, trust region |step| <= 1. The final state of every arm is
   the lowest-energy iterate of its last --final-window steps (same rule for all arms).
     S   plain SR for the whole budget.
     N   NULL, matched restarts: --null-k cold starts (start 0 = the shared start, start
         j>0 = fresh UHF + NNBF init with seed s + 7919 j), each trained
         L = (warm-up + proposal steps of arm A) // null-k steps, scored by the SAME
         fixed-node score as arm A; the winner gets the rest of the budget.
     A   SNO-FN: --warmup SR steps, then --cycles cycles. In each cycle the 1-RDM of the
         current state is computed per spin, averaged over the space group, and
         diagonalised (degeneracies split by an infinitesimal mirror-parity term, so
         natural orbitals (NOs) have definite parities). Candidates replace the reference
         orbitals Phi0 (backflow weights kept) by: the top-N_sigma NOs ("sno"); the same
         with the last occupied and first empty NO exchanged for up, down, or both
         ("swap_u", "swap_d", "swap_ud"). The incumbent and each candidate are relaxed
         --relax SR steps and scored by the fixed-node energy E_FN[|psi|] (one ten Haaf
         solve with guide |psi_cand|, the quantity lattice FN-GFMC estimates); the best
         candidate replaces the incumbent only if its score is lower. The rest of the
         budget is plain SR.
     AE  ablation of A: identical, but candidates are scored by the variational energy
         after --relax steps (the round-1 OSBH acceptance rule).
     B   FCD: --warmup SR steps, then --cycles cycles. Each cycle: for each cap c in
         --caps, from the incumbent psi_ref run --excursion SR steps on
         E + lam * max(0, F - c)^2 with F = |<psi_ref|psi>|^2/(<psi_ref|psi_ref><psi|psi>),
         lam = --lam, then --relax plain SR steps; the incumbent is relaxed --relax steps;
         all are scored by E_FN[|psi|] and the best is kept. Rest of budget: plain SR.
     W   WITNESS (oracle, diagnostic only): --pretrain natural-gradient steps on
         -log F(psi_0, psi) from the shared start, then plain SR for --budget steps.
         It asks whether the NNBF family has a better-sign basin that SR keeps once there.
3. For every final state: E_var, E_sign (= min over L-BFGS-B starts |psi|, |phi_FN|,
   |psi_0| and the fixed-node values; P1.1 definition, an upper bound on
   min_{a>=0} a^T S H S a / a^T a), E_FN (ten Haaf, --fn-iters self-consistent
   iterations, P1.1 code), the sign-mismatch weight w = sum_{s_theta s_0 < 0} psi_0^2,
   overlaps |<E_k|psi>|^2 with the ED states, and <Tx>,<Ty>,<Mx>,<My>. For arm S it
   also computes E_sign of the sign of the psi_0-irrep projection of psi (diagnostic:
   is the S sign error symmetry contamination?) and runs ROUTE P, the irrep scan with
   fixed-node-ranked selection: psi is projected on every real 1-D irrep chi of the space
   group (generator eigenvalues Tx, Ty, Mx, My in {+1,-1}; Tx=-1 only for even Lx, Ty=-1
   only for even Ly), each projection is scored by its variational energy E_var and by the
   guided fixed-node score E_FN[|P_chi psi|]; the irrep chosen by each score is recorded
   together with whether it is psi_0's irrep, and E_sign of the FN-chosen projection is
   computed. Route P costs no SR steps (post-processing, |G| = 48 times the amplitude cost).
4. Writes JSON (rewritten after every arm).

Decision rule (pre-committed; applied by --aggregate over all seed JSONs)
-----------------------------------------------------------------------
  e_X(i) = E_sign(X, seed i) - E_0. Baseline b(i) = min(e_S(i), e_N(i)).
  Reduction for route R in {A, B}: rho_R(i) = (b(i) - e_R(i)) / b(i).
  dEvar_R(i) = E_var(R, i) - min(E_var(S, i), E_var(N, i)).
  PASS(R)      if median rho_R >= 0.25 AND rho_R > 0 on >= ceil(7n/8) seeds
               AND median dEvar_R <= 0.01 (t).
  FAIL(R)      if median rho_R < 0.10 OR rho_R > 0 on <= n/2 seeds.
  AMBIGUOUS(R) otherwise; action: rerun with 16 seeds (array 8-23 added); kill R unless
               the 24-seed set gives PASS.
  Premise (witness): gW(i) = (e_S(i) - e_W(i)) / e_S(i).
               BASIN if median gW >= 0.30 and gW > 0 on >= ceil(7n/8) seeds;
               NO-BASIN if median gW < 0.10; otherwise UNCLEAR.
               A route PASS under NO-BASIN is reported as "PASS (optimizer speed-up,
               not basin escape)".
  Projection bar: a route PASS is relabelled "PASS but DOMINATED by projection" if the
               median e_R is not below the median E_sign - E_0 of the psi_0-irrep
               projection of the S state (standard quantum-number projection, |G| times
               the amplitude cost); the surviving claim is then only the cost saving.
  Ablation:    rho_A - rho_AE (median) is reported: it says whether the FN gate matters.
  Route P:     fn_c, var_c = number of seeds on which the FN score / E_var picks psi_0's
               irrep; rho_P(i) = (e_S(i) - e_P(i)) / e_S(i) with e_P from the FN-chosen
               projection.
               PASS(P) if fn_c >= ceil(7n/8) AND var_c <= fn_c - 2 AND median rho_P >= 0.25.
               FAIL(P) if fn_c <= n - 3, or var_c >= fn_c (then the FN gate adds nothing
               over energy-ranked projection, which is standard practice).
               AMBIGUOUS(P) otherwise; same rerun action as for A and B.
  Aggregation needs n >= 8 seeds with all of S, N, A, B (W, AE optional); it is done
  separately per instance. Overall route verdict = verdict on "main" (sign half). The
  "comp" verdict decides whether the claim extends to the competitor half: a route that
  PASSes on main but not on comp is reported as "PASS (sign half only)".

Usage
-----
    python3 micro_test.py [options]
    python3 micro_test.py --aggregate results

Options
-------
  --instance {main,comp,smoke}  main: 4x3 PBC, N_up=N_dn=4, U=8, t'=-0.25 (P1.1 instance 1,
                    D=245025). SIGN HALF ONLY: its first excited level (0.086t up) is a
                    spin triplet at k=(pi,+-2pi/3); inside the ground-state sector (K=0,
                    both mirrors even, S=0) the next level is 0.515t up, so it has no
                    same-sector near-degenerate competitor.
                    comp: same cluster at t'=-0.32, inside the same-sector avoided crossing
                    (minimum in-sector gap 0.273t between t'=-0.33 and -0.31, where a
                    d-wave/short-range-AF state and a period-4 stripe exchange character;
                    ED evidence tests/P3.2_biased_ensemble_r2/ed_precheck_output.txt).
                    Carries the competitor half; same D.
                    smoke: 3x3 PBC, 3+3, U=8, t'=-0.25 (D=7056), only for code checks.
                    Default main.
  --seed INT        seed s of the shared start (default 1234 = P1.1 seed). The sbatch
                    script uses 1234 + SLURM_ARRAY_TASK_ID.
  --arms LIST       comma-separated subset of S,N,A,AE,B,W (default "S,N,A,AE,B,W").
  --width INT       NNBF hidden width (default 32; must be >= 32 for a decisive run).
  --budget INT      SR steps per arm (default 1200).
  --warmup INT      warm-up SR steps of arms A, AE, B (default 300).
  --cycles INT      proposal cycles of arms A, AE, B (default 2).
  --relax INT       relaxation SR steps per candidate / incumbent (default 40).
  --excursion INT   biased SR steps per FCD excursion (default 60).
  --caps LIST       fidelity caps c for FCD, comma-separated in (0,1) (default "0.8,0.5").
  --lam FLOAT       FCD penalty strength lambda in units of t (default 2.0).
  --null-k INT      number of cold starts of the null arm N (default 3).
  --pretrain INT    fidelity pre-training steps of the witness W (default 300).
  --final-window INT  final state = lowest-energy iterate of the last this-many steps
                    (default 100).
  --sr-lr FLOAT     SR step size (default 0.05).  --sr-shift FLOAT  diagonal shift (1e-3).
  --sr-samples INT  configurations for the SR metric (default 2000).
  --chunk INT       configurations per forward chunk (default 65536).
  --fn-iters INT    self-consistent ten Haaf iterations in the final evaluation (default 4).
  --fn-floor FLOAT  guide floor relative to max (default 1e-3).
  --lbfgs-iters INT max L-BFGS-B iterations per start (default 3000).
  --n-ed INT        ED eigenpairs (default 4, at least 3).
  --out PATH        JSON path (default results/seed<s>_<instance>.json next to this
                    script). Existing files are not overwritten unless --overwrite 1.
  --overwrite {0,1} default 0.
  --checks-only {0,1}  1: run correctness checks only (default 0). Checks always run first.
  --aggregate DIR   no computation: apply the decision rule to every *.json in DIR.
"""
